"""Build the results page of the rerun session from its CSVs.

  python tools/build_rerun_results.py           # write reports/five-model-rerun-h100-v1/results.md
  python tools/build_rerun_results.py --check   # fail if that page is stale

Standard library only, no GPU. It reads the tables that bench/session_publish.py writes on the node
(serving, decode intervals, live state, trace components, expert routing, natural answers, pilot) and
never a raw run. A table whose CSV is missing or empty is printed as pending, not as zero.
"""
import collections
import csv
import json
from pathlib import Path
import statistics as st
import sys

ROOT = Path(__file__).resolve().parents[1]
STUDY = 'five-model-rerun-h100-v1'
BASE = ROOT / 'reports' / STUDY
OUT = f'reports/{STUDY}/results.md'
MODELS = [('v4-0731', '0731'), ('v41', 'V4.1'), ('mimo-v26', 'MiMo'), ('qwen-38-bf16', 'Qwen'), ('glm-53', 'GLM')]
BUCKETS = ['1k', '16k', '64k', '128k']
LABEL = {'1k': '1K', '16k': '16K', '64k': '64K', '128k': '128K'}


def rows(name):
    p = BASE / name
    if not p.is_file():
        return []
    with p.open(encoding='utf-8', newline='') as f:
        return list(csv.DictReader(f))


def num(r, k):
    return float(r[k]) if r.get(k) not in (None, '') else None


def cell(vals, fmt, sd=True):
    vals = [v for v in vals if v is not None]
    if not vals:
        return 'pending'
    if len(vals) == 1:
        return f'{fmt.format(vals[0])} (1 block)'
    text = f'{fmt.format(st.mean(vals))} ± {fmt.format(st.stdev(vals))}' if sd else fmt.format(st.mean(vals))
    return text if len(vals) == 3 else f'{text} ({len(vals)} blocks)'


def table(head, body):
    return ['| ' + ' | '.join(head) + ' |', '| ' + ' | '.join('---' for _ in head) + ' |'] + \
        ['| ' + ' | '.join(str(x) for x in r) + ' |' for r in body]


def timeline():
    p = BASE / 'study/_logs/timeline.jsonl'
    steps = {}
    if p.is_file():
        for line in p.read_text(encoding='utf-8').splitlines():
            e = json.loads(line)
            if e['event'] == 'end':
                steps[e['step']] = e
    return steps


def generate():
    steps = timeline()
    serving = [r for r in rows('serving.csv') if r['valid'] == 'True']
    runtime = next((r['runtime'] for r in rows('serving.csv') + rows('pilot.csv') + rows('natural.csv')), 'pending')
    out = [f'# Rerun session results: `{STUDY}`', '',
           f'Generated by `python tools/build_rerun_results.py` from the CSVs in this folder. Build: vLLM `{runtime}`. '
           'All five models on one 8×H100 node, tensor parallel 8 plus expert parallel, prefix caching off, speculation off. '
           'The session plan is [target.md](../../target.md#the-15-hour-session); when each step finished is in '
           '[timeline.md](timeline.md). **A cell that says pending has not been measured yet.**', '',
           'Read each table for what it is: serving and decode-interval values are elapsed time from plain launches; '
           'trace components are GPU kernel sums from a separate profiler launch, and a kernel sum is not a latency; '
           'live state is the usage gauge times the reserved pool, an approximation of bytes held by live requests.', '']

    done = [name for mk, name in MODELS if steps.get(f'timing:{mk}:3', {}).get('outcome') == 'done']
    out += ['## Status', '',
            f'Diagnostics finished: {", ".join(n for mk, n in MODELS if steps.get(f"diag:{mk}", {}).get("outcome") == "done") or "none yet"}. '
            f'All three timing blocks finished: {", ".join(done) or "none yet"}.', '']

    # ------------------------------------------------------------------ serving
    out += ['## Serving with 2,048 output tokens', '',
            'Mean ± sample SD over launch-separated blocks; each block is one plain launch. One client: 12 requests. '
            'Sixteen clients: 48 requests. `c` is the client cap on open requests, not the engine batch.', '']
    for metric, title, fmt in (('output_tok_s', 'Output tokens per second', '{:.1f}'),
                               ('ttft_p50_ms', 'Time to first token, median per block (ms)', '{:.0f}'),
                               ('tpot_p50_ms', 'Time per output token, median per block (ms)', '{:.2f}')):
        body = []
        for b in BUCKETS[:3]:
            for c in ('1', '16'):
                body.append([LABEL[b], c] + [cell([num(r, metric) for r in serving
                                                   if (r['model'], r['bucket'], r['concurrency']) == (mk, b, c)], fmt)
                                             for mk, _ in MODELS])
        out += [f'### {title}', ''] + table(['Input', 'Clients'] + [n for _, n in MODELS], body) + ['']

    # ------------------------------------------------------------------ decode intervals
    iv = [r for r in rows('decode_intervals.csv') if r['valid'] == 'True']
    out += ['## Decode step time against context', '',
            'Unprofiled intervals of 512 tokens per request on the plain launches: B requests admitted together, the '
            'interval starts 16 tokens after the last first token, and nothing is admitted inside it. Milliseconds per '
            'engine step, mean ± sample SD over blocks. Batch 1 at 1K, 16K and 64K is the one-client TPOT above.', '']
    body = [[LABEL[b], B] + [cell([num(r, 'ms_per_step') for r in iv if (r['model'], r['bucket'], r['engine_B']) == (mk, b, B)],
                                  '{:.2f}') for mk, _ in MODELS]
            for b, B in (('1k', '8'), ('16k', '8'), ('64k', '8'), ('128k', '8'), ('128k', '1'))]
    out += table(['Context', 'Engine batch'] + [n for _, n in MODELS], body) + ['']
    bad = [r for r in rows('decode_intervals.csv') if r['valid'] != 'True']
    if bad:
        out += ['Intervals that did not hold their batch (recorded, not averaged): '
                + '; '.join(f'{dict(MODELS)[r["model"]]} {LABEL[r["bucket"]]} B={r["engine_B"]} block {r["block"]} ({r["problems"]})'
                            for r in bad) + '.', '']
    body = [[LABEL['128k']] + [cell([num(r, 'client_ttft_first_s') for r in iv
                                     if (r['model'], r['bucket'], r['engine_B']) == (mk, '128k', '1')], '{:.2f}')
                               for mk, _ in MODELS]]
    out += ['Time to first token of the single 128K request in the same launches, seconds (prompt processing with '
            'nothing else in the engine):', ''] + table(['Context'] + [n for _, n in MODELS], body) + ['']

    # ------------------------------------------------------------------ live state
    mem = rows('memory.csv')
    out += ['## Live state at the eight decode conditions', '',
            'One snapshot per condition in the diagnostics launch, taken when the last of B requests has produced its '
            'first token. KiB per token per GPU = usage gauge × reserved pool ÷ tokens the server counted (prompt plus '
            'generated). Multiply by eight for the node, replicated copies included. This shows which model stores less '
            'per token of a live request. It does not show what a prefix cache would keep or reuse: prefix caching was off.', '']
    body = []
    for b in BUCKETS:
        for B in ('1', '8'):
            line = [LABEL[b], B]
            for mk, _ in MODELS:
                r = next((x for x in mem if (x['model'], x['bucket'], x['live_sequences']) == (mk, b, B)), None)
                if r is None:
                    line.append('pending')
                elif r.get('capacity_limit') == 'True':
                    line.append('capacity limit')
                else:
                    v, g = num(r, 'live_kib_per_token_per_rank'), num(r, 'live_gib_8_ranks')
                    line.append('n/a' if v is None else f'{v:.2f} KiB ({g:.2f} GiB on 8)')
            body.append(line)
    out += table(['Context', 'Live requests'] + [n for _, n in MODELS], body) + ['']
    body = []
    for mk, name in MODELS:
        r = next((x for x in mem if x['model'] == mk), None)
        body.append([name] + (['pending'] * 3 if r is None else
                              [f'{num(r, "weights_gib_per_rank"):.2f} GiB' if num(r, 'weights_gib_per_rank') else 'n/a',
                               f'{num(r, "pool_gib_per_rank"):.2f} GiB' if num(r, 'pool_gib_per_rank') else 'n/a',
                               f'{int(num(r, "pool_tokens")):,}' if num(r, 'pool_tokens') else 'n/a']))
    out += ['Weights and reserved pool per GPU, from each server log:', ''] + \
        table(['Model', 'Weights loaded', 'KV pool reserved', 'Pool capacity in tokens (runtime accounting)'], body) + ['']

    # ------------------------------------------------------------------ trace components
    comp = rows('components.csv')
    out += ['## Attention path and expert time in the traces', '',
            'GPU kernel milliseconds per engine step, mean over the eight ranks, from the idle-profiler launch. '
            'Attention path = core + search (indexer, top-k) + recurrent update + state preparation; projections are '
            'inside the mixed dense-GEMM column and are not included. Prefill rows are the last full 8,192-token chunk '
            'of one request (at 1K, its single step). At 1K and 16K that chunk is the first step after the profiler '
            'starts, where all-reduce kernels wait for the other ranks, so the last table leaves communication out.', '']
    if not comp:
        out += ['Pending: the traces are classified after each diagnostics launch.', '']
    else:
        def mean(mk, capture, group, keys):
            rs = [r for r in comp if (r['model'], r['capture'], r['group']) == (mk, capture, group)]
            if not rs:
                return None
            return sum(sum(num(r, k) or 0 for k in keys) for r in rs) / len(rs)
        att = ['attention_core_ms', 'indexer_topk_ms', 'recurrent_attention_ms', 'qkv_rope_kvcache_ms']
        ffn = ['moe_expert_gemm_ms', 'moe_route_combine_ms']
        fmt = lambda v: 'pending' if v is None else (f'{v:.1f}' if v >= 20 else f'{v:.2f}')
        for title, keys in (('Attention path', att), ('Attention core only', att[:1]), ('Search (indexer, top-k) only', att[1:2]),
                            ('Recurrent update only', att[2:3]), ('Experts and routing', ffn),
                            ('All kernels except communication', None)):
            body = []
            for cap, group, lab in [(f'prefill{b}', 'last_full_chunk', f'Prefill chunk, {LABEL[b]}') for b in BUCKETS] + \
                    [(f'decode{b}_B{B}', 'decode_steps', f'Decode step, {LABEL[b]}, B={B}') for B in (1, 8) for b in BUCKETS]:
                if keys is None:  # all-reduce durations include waiting for other ranks, most of all right after profiler start
                    vals = [(mean(mk, cap, group, ['kernel_sum_ms']), mean(mk, cap, group, ['allreduce_ms', 'allgather_other_comm_ms']))
                            for mk, _ in MODELS]
                    body.append([lab] + [fmt(None if a is None else a - b) for a, b in vals])
                    continue
                body.append([lab] + [fmt(mean(mk, cap, group, keys)) for mk, _ in MODELS])
            out += [f'### {title} (ms, kernel sum)', ''] + table(['Capture'] + [n for _, n in MODELS], body) + ['']

    # ------------------------------------------------------------------ expert routing
    routing = rows('routing.csv')
    out += ['## Expert sparsity: nominal against realized', '',
            'From the runtime\'s own capture of the router\'s selected expert IDs, in a separate instrumented launch '
            '(no speed claim). Share of experts used in one engine step, mean over routed layers and steps.', '']
    if not routing:
        out += ['Pending: stage 3 of the session.', '']
    else:
        body = []
        for cond, lab in (('decode1k_B1', 'One decode token'), ('decode1k_B8', '8 decode tokens (B=8)'),
                          ('decode1k_B64', '64 decode tokens (B=64)'), ('prefill16k_first_chunk', 'One 8,192-token prefill chunk')):
            line = [lab]
            for mk, _ in MODELS:
                r = next((x for x in routing if (x['model'], x['condition']) == (mk, cond)), None)
                line.append('pending' if r is None else
                            f'{100 * num(r, "share_of_experts_per_step_mean"):.1f}% ({num(r, "distinct_per_step_mean"):.1f} of {r["n_experts"]})')
            body.append(line)
        line = ['Nominal k of N']
        for mk, _ in MODELS:
            r = next((x for x in routing if x['model'] == mk), None)
            line.append('pending' if r is None else f'{r["k"]} of {r["n_experts"]} ({100 * num(r, "nominal_share"):.1f}%)')
        out += table(['Step'] + [n for _, n in MODELS], [line] + body) + ['']

    # ------------------------------------------------------------------ natural answers and pilot
    nat = [r for r in rows('natural.csv') if r['kind'] == 'natural_eos']
    out += ['## Natural-ending answers (12 prompts per model, 2K cap)', '',
            'A check that each deployment answers and stops by itself, not a quality ranking. GLM has no thinking-off '
            'switch and runs with `reasoning_effort=low`.', '']
    body = []
    for mk, name in MODELS:
        rs = [r for r in nat if r['model'] == mk]
        if not rs:
            body.append([name, 'pending', '', '', '']); continue
        toks = [num(r, 'completion_tokens') for r in rs if num(r, 'completion_tokens') is not None]
        body.append([name, f'{sum(r["finish_reason"] == "stop" for r in rs)} of {len(rs)}',
                     f'{st.median(toks):.0f} (max {max(toks):.0f})' if toks else 'n/a',
                     str(sum(r['finish_reason'] == 'length' for r in rs)),
                     str(sum((num(r, 'reasoning_chars') or 0) > 0 for r in rs))])
    out += table(['Model', 'Stopped by itself', 'Output tokens, median', 'Hit the 2K cap', 'Answers with reasoning text'], body) + ['']

    pilot = rows('pilot.csv')
    out += ['## Pilot of the serving points (diagnostics launch)', '',
            'Auxiliary requests on the idle-profiler launch, to check that every session point is valid and to estimate '
            'run time. These are not timing results.', '']
    body = [[dict(MODELS)[r['model']], LABEL[r['bucket']], r['concurrency'], r['n'], r['valid'],
             f'{num(r, "duration_s"):.0f}' if num(r, 'duration_s') else '',
             f'{num(r, "estimated_full_run_s"):.0f}' if num(r, 'estimated_full_run_s') and r['valid'] == 'True' else '',
             r['problems']]
            for r in pilot]
    out += (table(['Model', 'Input', 'Clients', 'Requests', 'Valid', 'Seconds', 'Estimated full run, s', 'Problems'], body)
            if body else ['Pending.']) + ['']
    return {OUT: '\n'.join(out)}


def main():
    stale = False
    for rel, body in generate().items():
        p = ROOT / rel
        if '--check' in sys.argv:
            if not p.is_file() or p.read_text(encoding='utf-8') != body:
                print('stale:', rel); stale = True
        elif BASE.is_dir():
            p.write_text(body, encoding='utf-8', newline='\n')
            print('wrote', rel)
    return 1 if stale else 0


if __name__ == '__main__':
    sys.exit(main())
